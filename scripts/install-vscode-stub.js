'use strict';

/**
 * Creates a local `node_modules/vscode` shim that re-exports the test double.
 *
 * Why this exists:
 *   The extension sources do `require('vscode')` at module scope. Outside the
 *   VS Code Extension Host that specifier does not resolve, so the modules
 *   cannot be loaded by a plain Node test runner. Vitest externalises CommonJS
 *   dependencies, so a `resolve.alias` in the config is not enough for the
 *   untransformed `require()` calls inside the sources.
 *
 *   Providing a real (git-ignored, generated) package on disk makes the
 *   resolution work for every consumer: Vitest, plain `node`, and any future
 *   tooling. Nothing in this file ships to users — `node_modules/**` is already
 *   excluded by `.vscodeignore`.
 *
 * Run automatically via the `postinstall` script. Safe to run repeatedly.
 */

const fs = require('node:fs');
const path = require('node:path');

const repoRoot = path.resolve(__dirname, '..');
const shimDir = path.join(repoRoot, 'node_modules', 'vscode');
const stubPath = path.join(repoRoot, 'test', 'helpers', 'vscode-stub.js');

if (!fs.existsSync(stubPath)) {
  console.error(`[vscode-stub] missing test double at ${stubPath}`);
  process.exit(1);
}

fs.mkdirSync(shimDir, { recursive: true });

fs.writeFileSync(
  path.join(shimDir, 'package.json'),
  `${JSON.stringify(
    {
      name: 'vscode',
      version: '0.0.0-test-stub',
      private: true,
      description: 'Local test double for the VS Code API (generated, do not edit)',
      main: 'index.js',
    },
    null,
    2
  )}\n`
);

// Resolve relative to this repo so the shim works from any cwd.
const relativeStub = path
  .relative(shimDir, stubPath)
  .split(path.sep)
  .join('/');

fs.writeFileSync(
  path.join(shimDir, 'index.js'),
  `'use strict';\n// Generated by scripts/install-vscode-stub.js - do not edit.\nmodule.exports = require(${JSON.stringify(relativeStub)});\n`
);

console.log('[vscode-stub] installed test double at node_modules/vscode');
